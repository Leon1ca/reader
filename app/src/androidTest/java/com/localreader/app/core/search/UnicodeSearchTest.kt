/** Same-device ICU oracle, independent authored source intervals, and hostile read cuts. */
class UnicodeSearchTest {
    private lateinit var root: File
    @Before fun setup() {
        root = File(InstrumentationRegistry.getInstrumentation().targetContext.cacheDir, "unicode-search-${UUID.randomUUID()}").apply { mkdirs() }
    }
    @After fun cleanup() { root.deleteRecursively() }
    private fun document(text: String, cuts: List<Int> = emptyList()) = object : CanonicalDocument {
        override val length = text.length.toLong()
        override fun slice(start: Long, count: Int) = text.substring(start.toInt(), minOf(text.length, start.toInt() + count))
        override fun permits(range: SourceRange) = cuts.none { range.start < it && range.end > it }
    }
    private fun oracle(text: String): String {
        val nfkc = Normalizer2.getNFKCInstance()
        return nfkc.normalize(CaseMap.toLower().apply(Locale.ROOT, nfkc.normalize(text)))
    }
    @Test fun independentIntervalsAndEverySmallReadCutAgreeWithWholePlatformIcu() {
        val input = InstrumentationRegistry.getInstrumentation().context.assets.open("search-unicode-oracle.json").bufferedReader().use { JSONObject(it.readText()) }
        val cases = input.getJSONArray("cases")
        println("Search ICU=${VersionInfo.ICU_VERSION}, Unicode=${UCharacter.getUnicodeVersion()}")
        for (text in listOf(".İ.", "Aİ.", ".甲İ乙.")) {
            val edits = Edits();val output = StringBuilder()
            CaseMap.toLower().apply(Locale.ROOT, text, output, edits)
            fun units(value: String) = value.map { it.code.toString(16) }
            println("CaseMap input=${units(text)} output=${units(output.toString())}")
            val iterator = edits.fineIterator
            while (iterator.next()) println("FineEdit src=${iterator.sourceIndex()} dst=${iterator.destinationIndex()} old=${iterator.oldLength()} new=${iterator.newLength()} change=${iterator.hasChange()}")
        }
        for (i in 0 until cases.length()) {
            val item = cases.getJSONObject(i);val source = item.getString("source")
            val cuts = item.getJSONArray("paragraphCutsUtf16").let { array -> (0 until array.length()).map(array::getInt) }
            val doc = document(source, cuts)
            val expected = item.getJSONArray("expectedDeduplicatedSourceHits").let { array -> (0 until array.length()).map { j ->
                val range = array.getJSONObject(j);SourceRange(range.getLong("sourceStart"), range.getLong("sourceEnd"))
            } }
            assertEquals(item.getString("id"), item.getString("expectedNormalizedSource"), oracle(source))
            for (read in 1..maxOf(2, source.length)) for (lower in 1..maxOf(2, source.length)) {
                val normalizer = UnicodeSearchNormalizer(root, read, lower)
                normalizer.normalize(doc).use { normalized ->
                    assertEquals("${item.getString("id")}: $read/$lower", oracle(source), normalized.slice(0, normalized.length.toInt()))
                    assertEquals(item.getString("id"), expected, normalized.find(normalizer.query(item.getString("query")), doc).ranges)
                }
            }
        }
        assertTrue(root.listFiles()!!.isEmpty())
    }
    @Test fun expansionAfterUnchangedPrefixesAndAcrossDefaultCaseWindowsHasExactSources() {
        for (prefix in listOf(101, 16383, 16384, 16385)) {
            val source = "甲".repeat(prefix) + "İİABC ΟΣ ΟΣΑ"
            val expected = "甲".repeat(prefix) + "i\u0307i\u0307abc ος οσα"
            // Java ROOT lowercase is a separate platform API, not generated by the tape.
            val javaLower = source.lowercase(Locale.ROOT)
            println("ROOT lowercase prefix=$prefix javaMatchesExpected=${javaLower == expected}")
            assertEquals(expected, javaLower)
            val doc = document(source)
            for (lower in listOf(1, 7, 16384)) {
                val normalizer = UnicodeSearchNormalizer(root, lowerSize = lower)
                normalizer.normalize(doc).use { normalized ->
                    var at = 0L;val actual = StringBuilder()
                    while (at < normalized.length) { val part = normalized.slice(at, 16384);actual.append(part);at += part.length }
                    assertEquals(expected, actual.toString())
                    assertEquals(listOf(SourceRange(prefix.toLong(), prefix.toLong() + 1), SourceRange(prefix.toLong() + 1, prefix.toLong() + 2)), normalized.find(normalizer.query("\u0307"), doc).ranges)
                    assertEquals(listOf(SourceRange(prefix.toLong() + 2, prefix.toLong() + 5)), normalized.find(normalizer.query("ABC"), doc).ranges)
                    assertEquals(listOf(SourceRange(prefix.toLong() + 6, prefix.toLong() + 8)), normalized.find(normalizer.query("ΟΣ"), doc).ranges)
                }
            }
            if (source.length <= 4096) assertEquals(expected, UnicodeSearchNormalizer(root).query(source))
        }
        assertTrue(root.listFiles()!!.isEmpty())
    }
    @Test fun wholeParagraphContextIsPreservedBeforeInverseMappedBoundaryFiltering() {
        data class Case(val source: String, val cuts: List<Int>, val query: String, val expected: List<SourceRange>)
        val cases = listOf(
            Case("ΟΣΑ", listOf(2), "οσ", listOf(SourceRange(0, 2))),
            Case("ΟΣΑ", listOf(2), "ΟΣ", emptyList()),
            Case("ΟΣ!", listOf(1), "ς", listOf(SourceRange(1, 2))),
            Case("ΟΣΑ", listOf(2), "οσα", emptyList()),
            Case("ABCD", listOf(2), "bc", emptyList()),
            Case("ABCD", emptyList(), "bc", listOf(SourceRange(1, 3))),
            Case("e\u0301", listOf(1), "é", emptyList()),
            Case("ΟΣ\nΑ", listOf(3), "ς", listOf(SourceRange(1, 2))),
            Case("ΟΣ\rΑ", listOf(3), "ς", listOf(SourceRange(1, 2))),
            Case("ΟΣ\r\nΑ", listOf(4), "ς", listOf(SourceRange(1, 2)))
        )
        for (case in cases) for (read in listOf(1, 2, 3, 7)) for (lower in listOf(1, 2, 3, 7)) {
            val normalizer = UnicodeSearchNormalizer(root, read, lower)
            val doc = document(case.source, case.cuts)
            normalizer.normalize(doc).use { normalized ->
                assertEquals(oracle(case.source), normalized.slice(0, normalized.length.toInt()))
                assertEquals(case.toString(), case.expected, normalized.find(normalizer.query(case.query), doc).ranges)
            }
        }
    }
    @Test fun giantOrdinaryDocumentAndLongIgnorableContextStayBoundedAndLinear() {
        val ignorable = '\u034f'
        assertTrue(UCharacter.hasBinaryProperty(ignorable.code, UProperty.CASE_IGNORABLE))
        assertTrue(Normalizer2.getNFKCInstance().hasBoundaryBefore(ignorable.code))
        val count = 1024 * 1024
        var reads = 0L
        val doc = object : CanonicalDocument {
            override val length = count.toLong() * 2 + 3
            override fun slice(start: Long, count: Int): String {
                val size = minOf(count.toLong(), length - start).toInt();reads += size
                return String(CharArray(size) { j -> when (start + j) { 0L -> 'A';1024L * 1024 + 1 -> 'Σ';length - 1 -> 'B';else -> ignorable } })
            }
            override fun permits(range: SourceRange) = true
        }
        val normalizer = UnicodeSearchNormalizer(root)
        normalizer.normalize(doc).use { normalized ->
            assertEquals("a", normalized.slice(0, 1))
            assertEquals("σ", normalized.slice(count.toLong() + 1, 1))
            assertEquals(listOf(SourceRange(count.toLong() + 1, count.toLong() + 2)), normalized.find(normalizer.query("σ"), doc).ranges)
            assertTrue("Source was rescanned quadratically: $reads", reads <= doc.length * 4)
        }
        // One giant real search unit does not imply an unbounded normalization buffer.
        val ordinary = object : CanonicalDocument {
            override val length = 1200L * 1024
            override fun slice(start: Long, count: Int) = "甲".repeat(minOf(count.toLong(), length - start).toInt())
            override fun permits(range: SourceRange) = true
        }
        normalizer.normalize(ordinary).use { normalized ->
            assertEquals(ordinary.length, normalized.length)
            assertEquals(SourceRange(ordinary.length - 1, ordinary.length), normalized.sourceRange(ordinary.length - 1, ordinary.length))
        }
        assertTrue(root.listFiles()!!.isEmpty())
    }
    @Test fun actualTwentyMiBFullwidthFileNormalizesCompletelyWithoutPerCharacterMapGrowth() {
        val file = File(root, "fullwidth-source.u16")
        // A real 20 MiB UTF-16 file, streamed to disk without a full-size String/ByteArray.
        file.outputStream().buffered(65536).use { output ->
            val block = ByteArray(65536) { if (it % 2 == 0) 0x21 else 0xff.toByte() }
            repeat(320) { output.write(block) }
        }
        assertEquals(20L * 1024 * 1024, file.length())
        java.io.RandomAccessFile(file, "r").use { input ->
            var maximumRead = 0
            val doc = object : CanonicalDocument {
                override val length = file.length() / 2
                override fun slice(start: Long, count: Int): String {
                    val size = minOf(count.toLong(), length - start).toInt();maximumRead = maxOf(maximumRead, size)
                    val bytes = ByteArray(size * 2);input.seek(start * 2);input.readFully(bytes)
                    return String(CharArray(size) { j -> ((bytes[j * 2].toInt() and 255) or ((bytes[j * 2 + 1].toInt() and 255) shl 8)).toChar() })
                }
                override fun permits(range: SourceRange) = true
            }
            val normalizer = UnicodeSearchNormalizer(root)
            normalizer.normalize(doc).use { normalized ->
                assertEquals(doc.length, normalized.length)
                assertEquals("a".repeat(32), normalized.slice(doc.length - 32, 32))
                assertEquals(SourceRange(doc.length - 1, doc.length), normalized.sourceRange(doc.length - 1, doc.length))
                assertTrue(maximumRead <= 16384)
                val work = root.listFiles()!!.single { it.isDirectory }
                assertEquals(40L, File(work, "final.map").length())
                assertTrue(work.walkTopDown().filter { it.isFile }.sumOf { it.length() } <= file.length() + 1024)
                assertTrue(normalized.find(normalizer.query("Ａ"), doc).truncated)
            }
        }
        assertEquals(listOf(file), root.listFiles()!!.toList())
    }
    @Test fun resourceFailureCancellationAndExactLimitHaveDistinctResultsAndCleanTapes() {
        val normalizer = UnicodeSearchNormalizer(root, unitLimit = 32)
        val under = document("e" + "\u0301".repeat(30))
        normalizer.normalize(under).use { assertEquals(oracle("e" + "\u0301".repeat(30)), it.slice(0, it.length.toInt())) }
        assertThrows(SearchResourceLimit::class.java) { normalizer.normalize(document("e" + "\u0301".repeat(33))) }
        assertTrue(root.listFiles()!!.isEmpty())
        var checks = 0
        assertThrows(CancellationException::class.java) {
            normalizer.normalize(document("甲".repeat(20000))) { if (++checks == 3) throw CancellationException("Canceled spike") }
        }
        assertTrue(root.listFiles()!!.isEmpty())
        for (count in listOf(200, 201)) {
            val doc = document("甲 ".repeat(count))
            normalizer.normalize(doc).use { normalized ->
                val result = normalized.find(normalizer.query("甲"), doc)
                assertEquals(200, result.ranges.size);assertEquals(count == 201, result.truncated)
            }
        }
    }
}
